CREATE SEQUENCE IF NOT EXISTS versao_cliente^^^
CREATE TABLE IF NOT EXISTS clientes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text NOT NULL,
    email text NOT NULL,
    versao bigint NOT NULL
)^^^
CREATE TABLE IF NOT EXISTS mudancas (
    versao bigint PRIMARY KEY,
    id bigint NOT NULL,
    nome text,
    email text,
    excluido boolean NOT NULL,
    registrado_em timestamptz NOT NULL DEFAULT clock_timestamp()
)^^^
CREATE OR REPLACE FUNCTION ordenar_gravacoes() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(42170);
    RETURN NULL;
END;
$$^^^
CREATE OR REPLACE FUNCTION registrar_mudanca() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    nova_versao bigint := nextval('versao_cliente');
BEGIN
    IF TG_OP = 'DELETE' THEN
        INSERT INTO mudancas (versao, id, excluido) VALUES (nova_versao, OLD.id, true);
        RETURN OLD;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.id <> NEW.id THEN
        RAISE EXCEPTION 'O identificador do cliente é imutável';
    END IF;
    NEW.versao := nova_versao;
    INSERT INTO mudancas (versao, id, nome, email, excluido)
    VALUES (nova_versao, NEW.id, NEW.nome, NEW.email, false);
    RETURN NEW;
END;
$$^^^
CREATE OR REPLACE TRIGGER ordenar_clientes BEFORE INSERT OR UPDATE OR DELETE ON clientes
FOR EACH STATEMENT EXECUTE FUNCTION ordenar_gravacoes()^^^
CREATE OR REPLACE TRIGGER capturar_clientes BEFORE INSERT OR UPDATE OR DELETE ON clientes
FOR EACH ROW EXECUTE FUNCTION registrar_mudanca()^^^
